let sec4 = fs.readFileSync('vercel_sec4.html', 'utf8').trim();
// Replace Next image URLs with local static URLs
// Example: srcSet="/_next/image?url=%2Fpages%2Ffront.png&amp;w=640&amp;q=75 640w, ..." src="/_next/image?url=%2Fpages%2Ffront.png&amp;w=3840&amp;q=75"
sec4 = sec4.replace(/srcSet="[^"]*"/g, '');
sec4 = sec4.replace(/src="\/_next\/image\?url=%2F([^&]+)&amp;[^"]*"/g, (match, p1) => {
  return `src="/${decodeURIComponent(p1)}"`;
});
sec4 = sec4.replace(/data-nimg="fill"/g, '');
sec4 = sec4.replace(/decoding="async"/g, '');

